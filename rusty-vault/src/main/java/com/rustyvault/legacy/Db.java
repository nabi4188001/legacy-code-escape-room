package com.rustyvault.legacy;

import java.sql.Connection;
import java.sql.DriverManager;
import java.sql.SQLException;
import java.sql.Statement;
import java.util.concurrent.atomic.AtomicInteger;

/**
 * DATABASE CONNECTION
 * CREATED 18.06.2003 - was Oracle, then DB2, now whatever the build server has
 */
public class Db {

    private static final AtomicInteger COUNTER = new AtomicInteger();

    public static Connection openEmpty() {
        try {
            Connection conn = DriverManager.getConnection(
                    "jdbc:h2:mem:vault" + COUNTER.incrementAndGet() + ";DB_CLOSE_DELAY=-1");
            Statement st = conn.createStatement();
            st.execute("CREATE TABLE customer ("
                    + "id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "
                    + "name VARCHAR(200) NOT NULL, "
                    + "city VARCHAR(200) NOT NULL, "
                    + "balance_cents BIGINT NOT NULL)");
            st.close();
            return conn;
        } catch (SQLException e) {
            throw new IllegalStateException("DATABASE DOWN: " + e.getMessage());
        }
    }
}
