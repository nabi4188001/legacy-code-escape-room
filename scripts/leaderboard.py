#!/usr/bin/env python3
"""RustyBench: turns the run logs in runs/ into bench/leaderboard.json and bench/LEADERBOARD.md.

A run counts when the model finished its attempts (status "completed", or no status in
older logs). A run that stopped because a model call failed (rate limit, bad model name,
outage) is counted separately as an error and says nothing about the model's ability.
"""
import glob
import json
import os
from collections import defaultdict

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
RUNS = os.path.join(ROOT, "runs")
OUT = os.path.join(ROOT, "bench")


def load_runs():
    runs = []
    for path in sorted(glob.glob(os.path.join(RUNS, "*", "*.json"))):
        with open(path) as f:
            run = json.load(f)
        run["_file"] = os.path.relpath(path, ROOT).replace(os.sep, "/")
        runs.append(run)
    return runs


def summarise(runs):
    done = [r for r in runs if r.get("status", "completed") == "completed"]
    errors = len(runs) - len(done)
    escaped = [r for r in done if r.get("escaped")]
    return {
        "runs": len(done),
        "errors": errors,
        "escapes": len(escaped),
        "escapeRate": round(len(escaped) / len(done), 3) if done else None,
        "firstTryEscapes": sum(1 for r in escaped if r.get("attemptsUsed") == 1),
        "avgAttemptsWhenEscaped": round(sum(r["attemptsUsed"] for r in escaped) / len(escaped), 2) if escaped else None,
        "avgTokens": round(sum(r.get("promptTokens", 0) + r.get("completionTokens", 0) for r in done) / len(done)) if done else None,
        "avgSeconds": round(sum(r.get("totalSeconds", 0) for r in done) / len(done)) if done else None,
    }


def cell(s):
    if s["runs"] == 0:
        return "error" if s["errors"] else "-"
    text = "%d/%d" % (s["escapes"], s["runs"])
    if s["escapes"]:
        text += " (%.1f)" % s["avgAttemptsWhenEscaped"]
    if s["errors"]:
        text += " +%d err" % s["errors"]
    return text


def main():
    runs = load_runs()
    by_model = defaultdict(list)
    by_pair = defaultdict(list)
    for r in runs:
        by_model[r["model"]].append(r)
        by_pair[(r["model"], r["room"])].append(r)
    rooms = sorted({r["room"] for r in runs})

    rows = []
    for model, model_runs in by_model.items():
        rows.append({"model": model, **summarise(model_runs),
                     "rooms": {room: summarise(by_pair[(model, room)]) for room in rooms if (model, room) in by_pair}})
    rows.sort(key=lambda r: (-(r["escapeRate"] or 0), r["avgAttemptsWhenEscaped"] or 99, -r["runs"]))

    os.makedirs(OUT, exist_ok=True)
    with open(os.path.join(OUT, "leaderboard.json"), "w") as f:
        json.dump({"rooms": rooms, "models": rows}, f, indent=2)
        f.write("\n")

    lines = ["# RustyBench", "",
             "Which models escape which rooms, how many attempts it takes, and what it costs. "
             "Generated by `scripts/leaderboard.py` from the run logs in `runs/`.", "",
             "## Overall", "",
             "| Model | Escaped | First try | Avg attempts when escaped | Avg tokens | Avg seconds |",
             "|---|---|---|---|---|---|"]
    for r in rows:
        rate = "-" if r["escapeRate"] is None else "%d/%d (%d%%)" % (r["escapes"], r["runs"], round(100 * r["escapeRate"]))
        err = " +%d err" % r["errors"] if r["errors"] else ""
        lines.append("| %s | %s%s | %s | %s | %s | %s |" % (
            r["model"], rate, err, r["firstTryEscapes"],
            r["avgAttemptsWhenEscaped"] if r["avgAttemptsWhenEscaped"] is not None else "-",
            "{:,}".format(r["avgTokens"]) if r["avgTokens"] is not None else "-",
            r["avgSeconds"] if r["avgSeconds"] is not None else "-"))
    lines += ["", "## Room by room", "",
              "Each cell is escapes/runs, with the average number of attempts of the escapes in brackets.", "",
              "| Model | " + " | ".join(rooms) + " |", "|---|" + "---|" * len(rooms)]
    for r in rows:
        lines.append("| %s | %s |" % (r["model"], " | ".join(cell(r["rooms"][room]) if room in r["rooms"] else "-" for room in rooms)))
    lines += ["", "A run that stopped because a model call failed (rate limit, outage) is shown as "
              "`err` and is left out of the percentages.", ""]
    with open(os.path.join(OUT, "LEADERBOARD.md"), "w") as f:
        f.write("\n".join(lines))
    print("\n".join(lines))


if __name__ == "__main__":
    main()
